std::string trim(const std::string& value) {
    std::size_t first = 0;
    while (first < value.size() && (value[first] == ' ' || value[first] == '\t')) {
        ++first;
    }
    std::size_t last = value.size();
    while (last > first && (value[last - 1] == ' ' || value[last - 1] == '\t')) {
        --last;
    }
    return value.substr(first, last - first);
}

bool readChoice(const std::string& prompt, int minValue, int maxValue, int& choice) {
    std::string line;
    while (true) {
        std::cout << prompt;
        if (!std::getline(std::cin, line)) {
            return false;
        }
        const std::string cleaned = trim(line);
        if (cleaned.size() == 1 && cleaned[0] >= '0' + minValue && cleaned[0] <= '0' + maxValue) {
            choice = cleaned[0] - '0';
            return true;
        }
        std::cout << "Некорректный ввод. Введите одну цифру от "
                  << minValue << " до " << maxValue << ".\n";
    }
}

